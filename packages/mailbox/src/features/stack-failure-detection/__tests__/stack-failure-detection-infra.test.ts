/**
 * Regression coverage for the "roleName failed to satisfy constraint: Member must have length less
 * than or equal to 64" deploy failure: `detectorRoleName`/`detectorFunctionName`/`ruleName`/
 * `execRoleName`/`smName` were all built as `<prefix>-<parentGroupId>-<full 36-char stack GUID>`, which
 * blew past the IAM/Lambda/EventBridge 64-char limit once the construct moved off a 3-char parent group
 * id (`ops`) onto the current `stack-failure-detection` construct id (23 chars). The synth tests in
 * `stack-failure-detection.test.ts` passed the whole time because nothing asserted name length.
 *
 * `execRoleName`/`smName` are gone entirely — the cloned self-clean state machine and execution role
 * they belonged to were removed in favor of registering the detector's targets on the shared
 * resource-sweeper (see stack-failure-detection-infra.ts). Two names are still explicitly generated by
 * this construct, each for a reason unrelated to breaking a cycle (see the class doc in
 * stack-failure-detection-infra.ts): `detectorFunctionName` (Lambda function, 64-char limit — pinned only
 * because the wrapper's `functionName` prop is required) and `detectorRoleName` (IAM role, 64-char
 * limit — pinned because the sweeper's worker IAM can't scope `iam:DeleteRole`/`iam:DeleteRolePolicy`
 * by `aws:ResourceTag` at all). The EventBridge rule is no longer pinned at all: its only previous
 * reason was breaking a construction-order cycle created by the detector's own RULE_ARN env var, and
 * that env var — along with all sweeper knowledge in the detector — is gone; the sweeper reads the
 * rule's real (auto-named) ARN from outside instead, an ordinary forward reference.
 */

import * as cdk from 'aws-cdk-lib';
import { App, BootstraplessSynthesizer } from 'aws-cdk-lib';
import { Template } from 'aws-cdk-lib/assertions';
import type { ICdkArtifactEngine } from '@serverlessinbox/mailbox-cdk-shared';
import { CdkArtifactEngine, PinnedResolver } from '@serverlessinbox/mailbox-cdk-shared';
import type { ArtifactVersionsEntry } from '@serverlessinbox/artifact-registry';
import { StackFailureDetection, SendStackFailuresMode } from '../stack-failure-detection';

function createTestArtifactResolver(stack: cdk.Stack): ICdkArtifactEngine {
  const packages: Record<string, ArtifactVersionsEntry> = {
    'mailbox-cdk': { version: '1.0.0', zone: 'regional' },
    'mailbox-go': { version: '1.0.0', zone: 'regional' },
  };
  const pinnedResolver = new PinnedResolver(stack, packages, 'test-artifacts', {});
  pinnedResolver.registerPackages(['mailbox-cdk', 'mailbox-go']);
  return new CdkArtifactEngine(stack, pinnedResolver);
}

/**
 * Length of an `Fn::Select` token used inside these names, keyed off which selection it actually
 * performs rather than assumed — this construct (and its pre-fix predecessor) uses two different
 * `Fn::Select` shapes with very different lengths, and conflating them would hide the exact bug this
 * suite exists to catch:
 * - `Fn.select(2, Fn.split('/', AWS::StackId))` — the raw stack GUID, always the fixed 36-char UUID
 *   format (`8-4-4-4-12`). This is what the pre-fix code embedded directly (the bug).
 * - `Fn.select(0, Fn.split('-', <that 36-char GUID>))` — just the UUID's first 8-char segment (the fix).
 * Both lengths are fixed by the UUID format, not by anything CloudFormation could vary at deploy time,
 * so each is a genuine worst case for its shape, not a guess.
 */
function selectedTokenLength(fnSelect: any): number {
  const [index, source] = fnSelect['Fn::Select'];
  const splitDelimiter = source?.['Fn::Split']?.[0];
  if (index === 2 && splitDelimiter === '/') return 36;
  if (index === 0 && splitDelimiter === '-') return 8;
  throw new Error(`Unrecognized Fn::Select token shape: ${JSON.stringify(fnSelect)}`);
}

/**
 * Worst-case concrete length of a physical name built as `Fn.join('', [...])`. Every literal string
 * part contributes its real length; every `Fn::Select` part contributes `selectedTokenLength` above.
 */
function worstCaseJoinLength(fnJoinToken: unknown): number {
  const fnJoin = fnJoinToken as { 'Fn::Join': [string, unknown[]] };
  const [delimiter, parts] = fnJoin['Fn::Join'];
  if (delimiter !== '') {
    throw new Error(`Expected an empty Fn::Join delimiter, got ${JSON.stringify(delimiter)}`);
  }
  return parts.reduce((sum: number, part: unknown) => {
    if (typeof part === 'string') return sum + part.length;
    if (part && typeof part === 'object' && 'Fn::Select' in (part as object)) {
      return sum + selectedTokenLength(part);
    }
    throw new Error(`Unexpected Fn::Join part shape: ${JSON.stringify(part)}`);
  }, 0);
}

/**
 * Picks out the resource whose explicit name (an `Fn::Join` token) starts with `prefix` — rather than
 * assuming exactly one resource of a given type is explicitly named. That assumption doesn't hold
 * against the pre-fix construct (which named both IAM roles), and which names are explicit vs.
 * CDK-auto-generated is a separate design fact from the length invariant this file exists to check.
 */
function findByNamePrefix(resources: unknown[], propertyName: string, prefix: string): any {
  const match = resources.find((r: any) => {
    const token = r.Properties?.[propertyName];
    const firstPart = token?.['Fn::Join']?.[1]?.[0];
    return typeof firstPart === 'string' && firstPart.startsWith(prefix);
  });
  if (!match) {
    throw new Error(`No resource found with an explicit ${propertyName} starting with ${JSON.stringify(prefix)}`);
  }
  return match;
}

describe('StackFailureDetectionInfra — physical name length', () => {
  let template: Template;

  beforeEach(() => {
    const app = new App({
      context: {
        'serverlessinbox:artifacts': {
          bucketBase: 'test-artifacts',
          packages: {
            'mailbox-cdk': { kind: 'release', version: '1.0.0' },
            'mailbox-go': { kind: 'release', version: '1.0.0' },
          },
        },
      },
    });
    const stack = new cdk.Stack(app, 'test-stack-diag-name-length', {
      env: { account: '111122223333', region: 'us-east-1' },
      synthesizer: new BootstraplessSynthesizer(),
    });
    const artifactResolver = createTestArtifactResolver(stack);

    // Same construct id as the real deploy site (`mailbox.ts`: `new StackFailureDetection(groups.ops,
    // 'stack-failure-detection', ...)`) — `parentGroupId` is this id, so this reproduces the real
    // 23-char value that pushed the pre-fix names over their limits.
    new StackFailureDetection(stack, 'stack-failure-detection', {
      mode: SendStackFailuresMode.ENABLED,
      artifactResolver,
    });

    template = Template.fromStack(stack);
  });

  it('the detector function name fits the Lambda function-name limit (64 chars)', () => {
    const fns = Object.values(template.findResources('AWS::Lambda::Function'));
    const detectorFn = findByNamePrefix(fns, 'FunctionName', 'mailbox-diag-fn-');

    const length = worstCaseJoinLength(detectorFn.Properties.FunctionName);
    expect(length).toBeLessThanOrEqual(64);
  });

  it('the detector role name fits the IAM role-name limit (64 chars)', () => {
    // Pinned (unlike a plain CDK-auto-named role) so the sweeper's worker IAM can scope
    // iam:DeleteRole/iam:DeleteRolePolicy by name prefix — those two actions don't support
    // aws:ResourceTag at all (see sweeper-infra.ts).
    const roles = Object.values(template.findResources('AWS::IAM::Role'));
    const detectorRole = findByNamePrefix(roles, 'RoleName', 'mailbox-diag-role-');

    const length = worstCaseJoinLength(detectorRole.Properties.RoleName);
    expect(length).toBeLessThanOrEqual(64);
  });

  it('the rule is CDK-auto-named, not pinned', () => {
    // No cycle to break anymore (see stack-failure-detection-infra.ts class doc) — the rule's ARN is
    // read from outside via a real token instead, so nothing requires a predictable name, and
    // auto-naming avoids the RETAIN-collision risk a pinned name would carry.
    const rules = Object.values(template.findResources('AWS::Events::Rule'));
    expect(rules).toHaveLength(1);
    expect((rules[0] as any).Properties.Name).toBeUndefined();
  });
});
