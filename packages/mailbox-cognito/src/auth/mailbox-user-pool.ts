import * as cdk from 'aws-cdk-lib';
import * as cognito from 'aws-cdk-lib/aws-cognito';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import * as acm from 'aws-cdk-lib/aws-certificatemanager';
import { Construct } from 'constructs';

import {
  AuthClientConfig,
  AuthPolicyConfig,
  MailboxAuthPolicies,
  MailboxAuthProviderBase,
  GenerateClientParams,
  JMAP_SCOPE_DESCRIPTIONS,
  OAUTH_CLIENT_ADMIN_UI,
  OAUTH_CLIENT_JMAP_UI,
  Permission,
  isDevelopmentMode,
  createArtifactResolverFromContext,
} from '@serverlessinbox/mailbox';

import type { AdminApiAddon, AdminApiAddonContext, AdminApiAddonProvider } from '@serverlessinbox/mailbox';

import { CognitoIdpUsersAdminApiAddon } from '../api/cognito-idp-users-addon';

import { makePhysicalName, slugifyLabel } from '../utils/resource-names';
import { PermissionToCognitoScope } from './scopemaps/cognito';
import { CognitoCustomMessageLambda } from '../lambdas/cognito-custom-message';

/**
 * Cognito-managed domain configuration
 */
export interface MailboxUserPoolCognitoDomain {
  type: 'cognito';
  /** Domain prefix (globally unique across AWS) */
  cognitoDomainPrefix: string;
}

/**
 * Custom domain configuration with certificate
 */
export interface MailboxUserPoolCustomDomain {
  type: 'custom';
  /** Custom domain name */
  domainName: string;
  /** ACM certificate for the domain */
  certificate: acm.ICertificate;
}

/**
 * Domain configuration for the user pool
 * Must be either Cognito-managed or custom, never both
 */
export type MailboxUserPoolDomain = MailboxUserPoolCognitoDomain | MailboxUserPoolCustomDomain;

export interface MailboxUserPoolProps {
  /**
   * Domain configuration - either Cognito-managed or custom
   * @example { type: 'cognito', cognitoDomainPrefix: 'my-auth' }
   * @example { type: 'custom', domainName: 'auth.example.com', certificate: cert }
   */
  domain: MailboxUserPoolDomain;

  /**
   * JMAP scopes to enable on this user pool
   * @default Object.values(Permission)
   */
  jmapScopes?: Permission[];

  /**
   * Whether to add admin and user groups
   * @default true
   */
  createDefaultGroups?: boolean;

  /**
   * Authorization mapping used by mailbox components.
   * Defaults to admin=['admin'], user=['user'].
   */
  authorization?: {
    adminGroups?: string[];
    userGroups?: string[];
  };

  authFlows?: cdk.aws_cognito.AuthFlow;

  /**
   * Custom message templates for Cognito emails (Custom Message trigger).
   * If provided, the trigger is attached automatically to this user pool.
   */
  customMessage?: {
    /** Optional login URL to include in the message (also used for sign-in link). */
    loginUrl?: string;

    /** Optional support/contact text appended to the email. */
    supportText?: string;
  };
}

/**
 * Opinionated JMAP user pool construct for mailbox servers.
 */
export class MailboxUserPool extends Construct implements MailboxAuthProviderBase, AdminApiAddonProvider {
  public readonly userPool: cognito.UserPool;
  public readonly userPoolDomain: cognito.UserPoolDomain;
  public readonly customMessageLambda?: CognitoCustomMessageLambda;
  private readonly jmapResourceServer: cognito.UserPoolResourceServer;
  private readonly jmapScopes: Permission[];
  private readonly resourceServerIdentifier: string = 'si';

  private readonly supportedIdentityProviders: cognito.UserPoolClientIdentityProvider[] = [
    cognito.UserPoolClientIdentityProvider.COGNITO,
  ];
  private readonly supportedIdentityProviderNames = new Set<string>(['COGNITO']);

  private authFlows: cdk.aws_cognito.AuthFlow;

  private readonly authzConfig: { adminGroups: string[]; userGroups: string[] };

  public readonly scopeMap: Record<string, Permission[]>;
  public readonly oauthDomain: string;
  public readonly issuer: string;
  public readonly authMethod = 'form';
  public readonly usePkce = true;

  public readonly policies: MailboxAuthPolicies;

  private readonly adminUiClients = new Map<string, AuthClientConfig>();
  private readonly jmapUiClients = new Map<string, AuthClientConfig>();
  private readonly headlessClients = new Map<string, AuthClientConfig>();

  get userPoolId(): string {
    return this.userPool.userPoolId;
  }

  /**
   * Register an additional identity provider to be enabled for all OAuth clients generated by this construct.
   * Intended for addon packages (e.g. SAML/OIDC federation providers).
   */
  public addSupportedIdentityProvider(providerName: string): void {
    if (this.supportedIdentityProviderNames.has(providerName)) {
      return;
    }

    this.supportedIdentityProviderNames.add(providerName);
    this.supportedIdentityProviders.push(cognito.UserPoolClientIdentityProvider.custom(providerName));
  }

  get tokenEndpoint(): string {
    return `https://${this.oauthDomain}/oauth2/token`;
  }

  get authorizationEndpoint(): string {
    return `https://${this.oauthDomain}/oauth2/authorize`;
  }

  private createOAuthClient(params: GenerateClientParams): AuthClientConfig {
    const scopes = params.permissions.map((scope: Permission) => ({
      scopeName: `${this.resourceServerIdentifier}/${PermissionToCognitoScope[scope]}`,
      scopeDescription: JMAP_SCOPE_DESCRIPTIONS[scope],
    }));

    const isClientCredentials = params.flow === 'client_credentials';
    const clientKey = slugifyLabel(params.name);

    const client = new cognito.UserPoolClient(this, `user-pool-client-${clientKey}`, {
      userPool: this.userPool,
      userPoolClientName: `mailbox-client-${clientKey}`,
      authFlows: this.authFlows,
      generateSecret: isClientCredentials,
      accessTokenValidity: cdk.Duration.hours(1),
      idTokenValidity: cdk.Duration.hours(1),
      refreshTokenValidity: cdk.Duration.days(30),
      preventUserExistenceErrors: true,
      supportedIdentityProviders: this.supportedIdentityProviders,
      oAuth: {
        flows: {
          authorizationCodeGrant: !isClientCredentials,
          implicitCodeGrant: false,
          clientCredentials: isClientCredentials,
        },
        scopes: [
          ...(isClientCredentials ? [] : [cognito.OAuthScope.OPENID, cognito.OAuthScope.EMAIL, cognito.OAuthScope.PROFILE]),
          ...scopes,
        ],
        ...(isClientCredentials
          ? {}
          : {
            callbackUrls: params.callbackUrls,
            logoutUrls: params.logoutUrls,
          }),
      },
    });

    // Ensure resource server exists before client scopes are validated.
    client.node.addDependency(this.jmapResourceServer);

    const requestedScopeList = params.permissions.map((permission: Permission) => {
      const scopeNameForOAuth = PermissionToCognitoScope[permission].replace(/\//g, '.');
      return `${this.resourceServerIdentifier}/${scopeNameForOAuth}`;
    });

    return {
      clientId: client.userPoolClientId,
      clientSecret: isClientCredentials ? client.userPoolClientSecret ?? undefined : undefined,
      requestScopeList: requestedScopeList,
      groups: params.groups ?? [],
    };
  }

  private addAudience(policy: AuthPolicyConfig, clientId: string): void {
    if (!policy.audiences.includes(clientId)) {
      policy.audiences.push(clientId);
    }
  }

  provisionHeadlessClient(params: {
    name: string;
    audiences: Array<'adminApi' | 'jmapApi'>;
    permissions: Permission[];
  }): AuthClientConfig {
    const existing = this.headlessClients.get(params.name);
    if (existing) {
      for (const audience of params.audiences) {
        if (audience === 'adminApi') {
          this.addAudience(this.policies.adminApi, existing.clientId);
        } else {
          this.addAudience(this.policies.jmapApi, existing.clientId);
        }
      }

      return existing;
    }

    const client = this.createOAuthClient({
      flow: 'client_credentials',
      name: params.name,
      permissions: params.permissions,
    });

    for (const audience of params.audiences) {
      if (audience === 'adminApi') {
        this.addAudience(this.policies.adminApi, client.clientId);
      } else {
        this.addAudience(this.policies.jmapApi, client.clientId);
      }
    }

    this.headlessClients.set(params.name, client);
    return client;
  }

  provisionAdminUiClient(params: { name: string; callbackUrls: string[]; logoutUrls: string[] }): AuthClientConfig {
    const resolvedName = `${OAUTH_CLIENT_ADMIN_UI}_${params.name}`;
    const existing = this.adminUiClients.get(resolvedName);
    if (existing) {
      return existing;
    }

    const client = this.createOAuthClient({
      flow: 'authorization_code',
      name: resolvedName,
      permissions: [Permission.ADMIN],
      groups: this.authzConfig.adminGroups,
      callbackUrls: params.callbackUrls,
      logoutUrls: params.logoutUrls,
    });

    this.addAudience(this.policies.adminApi, client.clientId);
    this.adminUiClients.set(resolvedName, client);
    return client;
  }

  provisionJmapUiClient(params: {
    name: string;
    callbackUrls: string[];
    logoutUrls: string[];
    permissions: Permission[];
  }): AuthClientConfig {
    const resolvedName = `${OAUTH_CLIENT_JMAP_UI}_${params.name}`;
    const existing = this.jmapUiClients.get(resolvedName);
    if (existing) {
      return existing;
    }

    const client = this.createOAuthClient({
      flow: 'authorization_code',
      name: resolvedName,
      permissions: params.permissions,
      groups: this.authzConfig.userGroups,
      callbackUrls: params.callbackUrls,
      logoutUrls: params.logoutUrls,
    });

    this.addAudience(this.policies.jmapApi, client.clientId);
    this.jmapUiClients.set(resolvedName, client);
    return client;
  }

  createAdminApiAddons(scope: Construct, ctx: AdminApiAddonContext): AdminApiAddon[] {
    return [
      new CognitoIdpUsersAdminApiAddon(scope, 'cognito-idp-users-admin-api', {
        artifactResolver: ctx.artifactResolver,
        auditEventsQueue: ctx.auditEventsQueue,
        pool: this,
      }),
    ];
  }

  getAdminUiConfig(): Record<string, unknown> {
    return { idp: { type: 'cognito' } };
  }

  getAuthorizationConfig(): { adminGroups: string[]; userGroups: string[] } {
    return this.authzConfig;
  }

  constructor(scope: Construct, id: string, props: MailboxUserPoolProps) {
    super(scope, id);

    this.authzConfig = {
      adminGroups: props.authorization?.adminGroups ?? ['admin'],
      userGroups: props.authorization?.userGroups ?? ['user'],
    };

    this.policies = {
      adminApi: {
        audiences: [],
        requireAnyOfGroups: this.authzConfig.adminGroups,
        requireAllScopes: [],
      },
      jmapApi: {
        audiences: [],
        requireAllScopes: [],
      },
    };

    this.authFlows = props.authFlows ?? {
      userPassword: false,
      userSrp: false,
    };

    this.jmapScopes = props.jmapScopes ?? Object.values(Permission);
    const createGroups = props.createDefaultGroups ?? true;

    this.scopeMap = this.buildScopeMap();

    // Admin API: always require admin scope. Group enforcement is applied for user tokens only
    // (client_credentials tokens don't carry groups).
    this.policies.adminApi.requireAllScopes = [this.toOAuthScope(Permission.ADMIN)];

    this.userPool = new cognito.UserPool(this, 'user-pool', {
      userPoolName: makePhysicalName(this, 'users', { maxLength: 128 }),
      selfSignUpEnabled: true,
      signInAliases: {
        email: true,
        username: true,
      },
      autoVerify: {
        email: true,
      },
      standardAttributes: {
        email: {
          required: false,
          mutable: true,
        },
      },
      passwordPolicy: {
        minLength: 8,
        requireLowercase: true,
        requireUppercase: true,
        requireDigits: true,
        requireSymbols: false,
      },
      mfa: cognito.Mfa.OPTIONAL,
      mfaSecondFactor: {
        sms: false,
        otp: true,
      },
      accountRecovery: cognito.AccountRecovery.EMAIL_ONLY,
      removalPolicy: isDevelopmentMode(this) ? cdk.RemovalPolicy.DESTROY : cdk.RemovalPolicy.RETAIN,
    });

    if (props.customMessage) {
      const artifactResolver = createArtifactResolverFromContext(this);

      this.customMessageLambda = new CognitoCustomMessageLambda(this, 'custom-message', {
        artifactResolver,
        loginUrl: props.customMessage.loginUrl,
        supportText: props.customMessage.supportText,
      });

      this.userPool.addTrigger(cognito.UserPoolOperation.CUSTOM_MESSAGE, this.customMessageLambda.fn);
    }

    this.issuer = `https://cognito-idp.${cdk.Stack.of(this).region}.amazonaws.com/${this.userPool.userPoolId}`;

    this.jmapResourceServer = this.userPool.addResourceServer('jmap-resource-server', {
      identifier: this.resourceServerIdentifier,
      userPoolResourceServerName: 'JMAP API',
      scopes: this.jmapScopes.map((scope: Permission) => ({
        scopeName: scope.replace(/\//g, '.'),
        scopeDescription: JMAP_SCOPE_DESCRIPTIONS[scope],
      })),
    });

    if (props.domain.type === 'custom') {
      this.userPoolDomain = this.userPool.addDomain('user-pool-domain', {
        customDomain: {
          domainName: props.domain.domainName,
          certificate: props.domain.certificate,
        },
      });
      this.oauthDomain = props.domain.domainName;
    } else {
      this.userPoolDomain = this.userPool.addDomain('user-pool-domain', {
        cognitoDomain: {
          domainPrefix: props.domain.cognitoDomainPrefix,
        },
      });
      this.oauthDomain = `${props.domain.cognitoDomainPrefix}.auth.${cdk.Stack.of(this).region}.amazoncognito.com`;
    }

    if (createGroups) {
      this.userPool.addGroup('admin', { groupName: 'admin' });
      this.userPool.addGroup('user', { groupName: 'user' });
    }

  }

  private toOAuthScope(permission: Permission): string {
    const scopeNameForOAuth = PermissionToCognitoScope[permission].replace(/\//g, '.');
    return `${this.resourceServerIdentifier}/${scopeNameForOAuth}`;
  }

  private buildScopeMap(): Record<string, Permission[]> {
    const scopeMap: Record<string, Permission[]> = {};

    for (const scope of this.jmapScopes) {
      const scopeNameForOAuth = scope.replace(/\//g, '.');
      const fullScopeName = `${this.resourceServerIdentifier}/${scopeNameForOAuth}`;
      scopeMap[fullScopeName] = [scope];
    }

    return scopeMap;
  }

  public grantAdminAccess(fn: lambda.IFunction): void {
    fn.addToRolePolicy(
      new iam.PolicyStatement({
        actions: [
          'cognito-idp:ListUsers',
          'cognito-idp:ListUsersInGroup',
          'cognito-idp:ListGroups',
          'cognito-idp:AdminListGroupsForUser',
          'cognito-idp:AdminCreateUser',
          'cognito-idp:AdminDeleteUser',
          'cognito-idp:AdminResetUserPassword',
          'cognito-idp:AdminSetUserPassword',
          'cognito-idp:AdminUpdateUserAttributes',
          'cognito-idp:AdminGetUser',
          'cognito-idp:AdminDisableUser',
          'cognito-idp:AdminEnableUser',
          'cognito-idp:AdminAddUserToGroup',
          'cognito-idp:AdminRemoveUserFromGroup',
        ],
        resources: [this.userPool.userPoolArn],
      }),
    );
  }
}
