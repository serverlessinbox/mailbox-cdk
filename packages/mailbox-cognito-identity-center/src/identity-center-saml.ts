import * as cognito from 'aws-cdk-lib/aws-cognito';
import { Construct } from 'constructs';

import { MailboxUserPool } from '@serverlessinbox/mailbox-cognito';

export interface IdentityCenterSamlMetadata {
  /**
   * The type of SAML metadata source: 'url' or 'file'.
   */
  readonly metadataType: string;

  /**
   * The metadata URL. Required when type is 'url'.
   */
  readonly url?: string;

  /**
   * The path to the metadata XML file. Required when type is 'file'.
   */
  readonly filePath?: string;
}

export interface IdentityCenterSamlFederationProps {
  /**
   * The mailbox Cognito user pool construct to attach the SAML IdP to.
   * This addon will also enable the IdP for all OAuth clients generated by `MailboxUserPool`.
   */
  readonly mailboxUserPool: MailboxUserPool;

  /**
   * SAML metadata for the Identity Center application.
   * Identity Center can provide either a metadata URL or raw XML.
   */
  readonly metadata: IdentityCenterSamlMetadata;

  /**
   * Cognito provider name (used in Hosted UI). Defaults to 'IdentityCenter'.
   */
  readonly providerName?: string;

  /**
   * Optional attribute mapping from SAML assertions into Cognito user attributes.
   */
  readonly attributeMapping?: cognito.AttributeMapping;

  /**
   * Optional IdP identifiers.
   * Useful when the IdP uses multiple entity IDs.
   */
  readonly idpIdentifiers?: string[];
}

/**
 * Attaches AWS IAM Identity Center (SAML) as a federated IdP to a Cognito User Pool.
 *
 * Note: Cognito remains the OIDC issuer for Mailbox; Identity Center is used for interactive login.
 */
export class IdentityCenterSamlFederation extends Construct {
  public readonly provider: cognito.UserPoolIdentityProviderSaml;

  constructor(scope: Construct, id: string, props: IdentityCenterSamlFederationProps) {
    super(scope, id);

    const metadata =
      props.metadata.metadataType === 'url'
        ? cognito.UserPoolIdentityProviderSamlMetadata.url(props.metadata.url!)
        : cognito.UserPoolIdentityProviderSamlMetadata.file(props.metadata.filePath!);

    this.provider = new cognito.UserPoolIdentityProviderSaml(this, 'identity-center-saml', {
      userPool: props.mailboxUserPool.userPool,
      name: props.providerName ?? 'IdentityCenter',
      metadata,
      attributeMapping: props.attributeMapping,
      identifiers: props.idpIdentifiers,
    });

    props.mailboxUserPool.addSupportedIdentityProvider(this.provider.providerName);
  }
}
